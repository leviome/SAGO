const {chromium}=require(process.env.PLAYWRIGHT_MODULE || '@playwright/test');
const fs=require('fs');
const path=require('path');
(async()=>{
 fs.mkdirSync('outputs',{recursive:true});
 const scene=fs.mkdtempSync(path.join(path.resolve('outputs'),'ground-browser-'));
 fs.copyFileSync('/home/pc/gaussian-splatting/output/for_seg1/point_cloud/iteration_30000/point_cloud.ply',path.join(scene,'scene.ply'),fs.constants.COPYFILE_FICLONE);
 fs.copyFileSync('/home/pc/gaussian-splatting/output/for_seg1/cameras.json',path.join(scene,'cameras.json'));
 const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:1920,height:1000}}), errors=[], actions=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('request',r=>{if(r.method()==='POST'&&r.url().endsWith('/api/jobs'))actions.push(r.postDataJSON().action);});
 const ready=async()=>{
  await page.locator('#busy-overlay').waitFor({state:'hidden',timeout:180000});
  if(await page.locator('#status').evaluate(el=>el.classList.contains('error')))throw Error(await page.locator('#status').innerText());
 };
 const up=()=>page.locator('[id^="up-"]').evaluateAll(els=>els.map(e=>Number(e.value)));
 const close=(a,b)=>a.every((x,i)=>Math.abs(x-b[i])<1e-5);
 const pick=async(x,y)=>{const r=await page.locator('#canvas').boundingBox();await page.mouse.click(r.x+r.width*x,r.y+r.height*y);};
 try {
  await page.addInitScript(()=>localStorage.setItem('sago-language','zh'));
    await page.goto('http://127.0.0.1:8080');
  await page.locator('#status').filter({hasText:'后端已连接'}).waitFor();
  if(!await page.locator('#ground-start').isDisabled())throw Error('Calibration enabled without scene');
  await page.locator('.manual-path summary').click();
  await page.locator('#path').fill(scene);
  await page.locator('#load').click();await ready();
  await page.locator('#ground-start').click();
  await page.locator('#ground-edit').waitFor();await ready();
  if(!await page.locator('#prompt-mode').isDisabled())throw Error('Prompt mode conflicts with ground picks');
  await pick(.27,.62);await page.locator('#ground-info').filter({hasText:'1/3'}).waitFor();await ready();
  await pick(.27,.62);await page.locator('#status.error').filter({hasText:'重合'}).waitFor();
  await pick(.78,.60);await page.locator('#ground-info').filter({hasText:'2/3'}).waitFor();await ready();
  await page.locator('#ground-undo').click();await page.locator('#ground-info').filter({hasText:'1/3'}).waitFor();await ready();
  await pick(.78,.60);await page.locator('#ground-info').filter({hasText:'2/3'}).waitFor();await ready();
  await pick(.52,.75);await page.locator('#ground-info').filter({hasText:'3/3'}).waitFor();await ready();
  if(await page.locator('#ground-apply').isDisabled())throw Error('Valid plane cannot be applied');
  await page.locator('#ground-details').click();
  fs.mkdirSync('test-results',{recursive:true});await page.screenshot({path:'test-results/ground-three-points.png'});
  await page.locator('#ground-apply').click();await page.locator('#ground-edit').waitFor({state:'hidden'});await ready();
  const normal=await up();if(Math.abs(Math.hypot(...normal)-1)>1e-5)throw Error('Nonunit normal');
  await page.locator('#camera-preset').selectOption('1');await ready();
  if(!close(normal,await up()))throw Error('Camera preset overwrote calibrated up');
  await page.locator('#ground-flip').click();await ready();
  if(!close(normal.map(x=>-x),await up()))throw Error('Flip did not update up');
  await page.locator('#ground-flip').click();await ready();
  if(!close(normal,await up()))throw Error('Second flip failed');
  await page.locator('#ground-start').click();await page.locator('#ground-edit').waitFor();await ready();
  await page.locator('#ground-cancel').click();await page.locator('#ground-edit').waitFor({state:'hidden'});await ready();
  if(!close(normal,await up()))throw Error('Cancel discarded saved plane');
  await page.screenshot({path:'test-results/ground-applied.png'});
  const knowledge=JSON.parse(fs.readFileSync(path.join(scene,'SAGO_knowledge.json'),'utf8'));
  if(!close(normal,knowledge.scenes['scene.ply'].up_vector))throw Error('Saved ground differs from accepted normal');
  await page.reload();await page.locator('#status').filter({hasText:'后端已连接'}).waitFor();
  await page.locator('.manual-path summary').click();await page.locator('#path').fill(scene);
  await page.locator('#load').click();await ready();
  if(!close(normal,await up()))throw Error('Reload did not restore ground normal');
  if(!(await page.locator('#ground-info').innerText()).includes('已从 SAGO_knowledge.json 读取'))throw Error('Restoration status missing');
  if(actions.includes('load_model'))throw Error('Ground calibration unexpectedly loaded SAM');
  if(errors.length)throw Error(errors.join('\n'));
  console.log('GROUND THREE-POINT PICKS, DUPLICATE VALIDATION, UNDO, APPLY, FLIP, PRESET, CANCEL, JSON SAVE/RELOAD, NO SAM LOAD OK',normal);
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
