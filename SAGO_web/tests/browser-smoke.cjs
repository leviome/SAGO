// npm install --prefix /tmp/sago-web-test @playwright/test (or set PLAYWRIGHT_MODULE)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '@playwright/test');
const fs = require('fs');
(async () => {
    const browser = await chromium.launch({ executablePath: process.env.SAGO_CHROME || '/usr/bin/google-chrome', headless: true, args:['--no-sandbox','--disable-dev-shm-usage'] });
    const page = await browser.newPage({ viewport:{width:1920,height:1000} });
    const errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    const automatic=()=>page.locator('#preview-status[data-state="done"]').waitFor({timeout:240000});
    const ready = () => page.locator('#busy-overlay').waitFor({state:'hidden',timeout:180000});
    await page.addInitScript(()=>localStorage.setItem('sago-language','zh'));
    await page.goto('http://127.0.0.1:8080');
    await page.locator('#status').filter({hasText:'后端已连接'}).waitFor();
    if(await page.locator('#seg-model').inputValue()!=='sam2')throw Error('Default model should be SAM2');
    if(await page.locator('#model-load-dialog').isVisible())throw Error('Model loaded before prompt mode');
    fs.mkdirSync('test-results',{recursive:true});
    await page.screenshot({path:'test-results/empty.png'});
    await page.locator('.manual-path summary').click();
    await page.locator('#path').fill(process.env.SAGO_TEST_SCENE || '/home/pc/gaussian-splatting/output/for_seg1');
    await page.locator('#load').click(); await ready();
    if (!(await page.locator('#scene-info').innerText()).includes('高斯')) throw new Error(await page.locator('#status').innerText());
    const viewport=await page.locator('#viewport').boundingBox();
    const rendered=await page.locator('#canvas').evaluate(el=>({w:el.width,h:el.height,rect:el.getBoundingClientRect().toJSON()}));
    if (rendered.w<=rendered.h || Math.abs(rendered.w/rendered.h-viewport.width/viewport.height)>.01) throw new Error('Rectangular render aspect mismatch');
    if (Math.abs(rendered.rect.width-viewport.width)>1 || Math.abs(rendered.rect.height-viewport.height)>1) throw new Error('Canvas does not fill viewport');
    await page.keyboard.press('m'); await ready();
    await page.locator('#model-load-dialog').waitFor({state:'visible'});
    if(await page.locator('#model-load-dialog').isVisible()) {
        await page.locator('#model-load-spinner').waitFor({state:'hidden',timeout:180000});
        if(!(await page.locator('#model-load-time').innerText()).includes('模型加载用时'))throw Error('Missing model load time');
        await page.locator('#model-load-dialog').waitFor({state:'hidden',timeout:10000});
    }
    if (!(await page.locator('#prompt-mode').isChecked())) throw new Error('M shortcut did not enter prompt mode');
    const canvas=page.locator('#canvas'); const rect=await canvas.boundingBox();
    await page.locator('#box-tool').click();
    await page.mouse.move(rect.x+rect.width*.25,rect.y+rect.height*.2);
    await page.mouse.down(); await page.mouse.move(rect.x+rect.width*.75,rect.y+rect.height*.8); await page.mouse.up();
    await automatic(); await ready();
    if (!(await page.locator('#timing').innerText()).includes('SAM2 分割：')) throw new Error('SAM2 timing missing');
    const candidates=await page.locator('#candidates button').count();
    if (candidates!==4) throw new Error('Missing SAM2 candidates: '+await page.locator('#status').innerText());
    await page.locator('#candidates button').nth(2).click();
    const applyRequest=page.waitForRequest(req=>req.url().endsWith('/api/jobs') && req.method()==='POST' && req.postDataJSON().action==='apply');
    await page.screenshot({path:'test-results/segmentation.png'});
    await page.locator('#drone').click();
    if((await applyRequest).postDataJSON().data.level!==2)throw Error('Wrong candidate submitted');
    await ready();
    if (!(await page.locator('#status').innerText()).includes('细化完成')) throw new Error(await page.locator('#status').innerText());
    if (!(await page.locator('#timing').innerText()).includes('分割合计：')) throw new Error('Total timing missing');
    if (await page.locator('.drone-thumb').count()!==6) throw new Error('Missing V-Drone view previews');
    await page.locator('.drone-thumb').first().click();
    await page.locator('#drone-render').evaluate(img=>img.decode());
    await page.locator('#drone-overlay').evaluate(img=>img.decode());
    if (!(await page.locator('#drone-view-title').innerText()).includes('+45°')) throw new Error('Wrong preview angle');
    const maskResponse=await page.request.get(await page.locator('#drone-mask-download').evaluate(a=>a.href));
    if (!maskResponse.ok() || !maskResponse.headers()['content-type'].includes('image/png')) throw new Error('Drone mask missing');
    await page.screenshot({path:'test-results/drone-view-detail.png'});
    await page.locator('#close-drone-view').click();
    await page.screenshot({path:'test-results/drone-result.png'});
    await page.locator('#object-name').fill('Browser smoke object');
    await page.locator('#save-object').click(); await ready();
    if (await page.locator('#objects .object').count()!==1) throw new Error('Object not saved');
    await page.locator('#undo').click(); await ready();
    if (await page.locator('#objects .object').count()!==0) throw new Error('Undo failed');
    await page.locator('#redo').click(); await ready();
    if (await page.locator('#objects .object').count()!==1) throw new Error('Redo failed');
    const downloadPromise=page.waitForEvent('download');
    await page.locator('#export-mask').click();
    const download=await downloadPromise;
    await download.saveAs('test-results/browser-mask.npy'); await ready();
    // Orbit after release should invalidate a captured view and remain interactive.
    await page.locator('#display button[data-mode="all"]').click(); await ready();
    await page.mouse.move(rect.x+rect.width*.5,rect.y+rect.height*.5); await page.mouse.down();
    await page.mouse.move(rect.x+rect.width*.55,rect.y+rect.height*.52); await page.mouse.up(); await ready();
    const selectedBefore=await page.locator('#stats').innerText();
    await page.locator('#prompt-mode').check(); await ready();
    const r2=await canvas.boundingBox();
    await page.mouse.move(r2.x+r2.width*.25,r2.y+r2.height*.2); await page.mouse.down();
    await page.mouse.move(r2.x+r2.width*.75,r2.y+r2.height*.8); await page.mouse.up();
    await automatic(); await ready();
    const maskDownload=page.waitForEvent('download');
    await page.locator('#export-2d').click(); await (await maskDownload).saveAs('test-results/browser-mask2d.png'); await ready();
    await page.locator('#drone').click();
    await page.locator('#cancel').waitFor({state:'visible'}); await page.locator('#cancel').click(); await ready();
    if (!(await page.locator('#status').innerText()).includes('取消')) throw new Error('Cancellation not reported');
    if (await page.locator('#stats').innerText()!==selectedBefore) throw new Error('Cancelled drone changed selection');
    await page.keyboard.press('m'); await ready();
    if(await page.locator('#model-load-dialog').isVisible()) {
        await page.locator('#model-load-spinner').waitFor({state:'hidden',timeout:180000});
        if(!(await page.locator('#model-load-time').innerText()).includes('模型加载用时'))throw Error('Missing model load time');
        await page.locator('#model-load-dialog').waitFor({state:'hidden',timeout:10000});
    }
    if (await page.locator('#prompt-mode').isChecked()) throw new Error('M shortcut did not leave prompt mode');
    await page.setViewportSize({width:720,height:1000});
    await page.screenshot({path:'test-results/mobile.png',fullPage:true});
    if (errors.length) throw new Error(errors.join('\n'));
    if (await page.locator('#status').evaluate(el=>el.classList.contains('error'))) throw new Error(await page.locator('#status').innerText());
    console.log('PASS: browser load, prompts, SAM2, six drone views and preview gallery/detail/download, object save, undo/redo, download, 2D mask, orbit, cancel rollback, responsive UI; no page errors.');
    await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
