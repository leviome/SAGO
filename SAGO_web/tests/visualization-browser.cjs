// npm install --prefix /tmp/sago-web-test @playwright/test (or set PLAYWRIGHT_MODULE)
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '@playwright/test');
const fs = require('fs');
(async () => {
    const browser = await chromium.launch({ executablePath: process.env.SAGO_CHROME || '/usr/bin/google-chrome', headless: true, args:['--no-sandbox','--disable-dev-shm-usage'] });
    const page = await browser.newPage({ viewport:{width:1920,height:1000} });
    const errors=[];
    page.on('pageerror',error=>errors.push(error.message));
    const automatic=()=>page.locator('#preview-status[data-state="done"]').waitFor({timeout:240000});
    const ready = () => page.locator('#busy-overlay').waitFor({state:'hidden',timeout:180000});
    await page.addInitScript(()=>localStorage.setItem('sago-language','zh'));
    await page.goto(process.env.SAGO_TEST_URL || 'http://127.0.0.1:8080');
    await page.locator('#status').filter({hasText:'后端已连接'}).waitFor();
    if(await page.locator('#seg-model').inputValue()!=='sam2')throw Error('Default model should be SAM2');
    if(await page.locator('#model-load-dialog').isVisible())throw Error('Model loaded before prompt mode');
    fs.mkdirSync('test-results',{recursive:true});
    await page.screenshot({path:'test-results/empty.png'});
    await page.locator('.manual-path summary').click();
    await page.locator('#path').fill(process.env.SAGO_TEST_SCENE || '/home/pc/gaussian-splatting/output/for_seg1');
    await page.locator('#load').click(); await ready();
    if (!(await page.locator('#scene-info').innerText()).includes('高斯')) throw new Error(await page.locator('#status').innerText());
    const viewport=await page.locator('#viewport').boundingBox();
    const rendered=await page.locator('#canvas').evaluate(el=>({w:el.width,h:el.height,rect:el.getBoundingClientRect().toJSON()}));
    if (rendered.w<=rendered.h || Math.abs(rendered.w/rendered.h-viewport.width/viewport.height)>.01) throw new Error('Rectangular render aspect mismatch');
    if (Math.abs(rendered.rect.width-viewport.width)>1 || Math.abs(rendered.rect.height-viewport.height)>1) throw new Error('Canvas does not fill viewport');
    await page.keyboard.press('m'); await ready();
    await page.locator('#model-load-dialog').waitFor({state:'visible'});
    if(await page.locator('#model-load-dialog').isVisible()) {
        await page.locator('#model-load-spinner').waitFor({state:'hidden',timeout:180000});
        if(!(await page.locator('#model-load-time').innerText()).includes('模型加载用时'))throw Error('Missing model load time');
        await page.locator('#model-load-dialog').waitFor({state:'hidden',timeout:10000});
    }
    if (!(await page.locator('#prompt-mode').isChecked())) throw new Error('M shortcut did not enter prompt mode');
    const canvas=page.locator('#canvas'); const rect=await canvas.boundingBox();
    await page.mouse.click(rect.x+rect.width*.25,rect.y+rect.height*.52);
    await automatic(); await ready();
    if (!(await page.locator('#timing').innerText()).includes('SAM2 分割：')) throw new Error('SAM2 timing missing');
    const candidates=await page.locator('#candidates button').count();
    if (candidates!==4) throw new Error('Missing SAM2 candidates: '+await page.locator('#status').innerText());
    await page.screenshot({path:'test-results/segmentation.png'});
    let overlay;
    page.on('response',async response=>{if(response.url().includes('/api/jobs/')){try{const j=await response.json();if(j.result?.visualization)overlay=j.result.visualization;}catch{}}});
    await page.locator('#drone').click(); await ready();
    if (!(await page.locator('#status').innerText()).includes('细化完成')) throw new Error(await page.locator('#status').innerText());
    if (!(await page.locator('#timing').innerText()).includes('分割合计：')) throw new Error('Total timing missing');
    if (await page.locator('.drone-thumb').count()!==6) throw new Error('Missing V-Drone view previews');
    if(!overlay?.bbox || overlay.route?.views.length!==6)throw Error('Missing world geometry');
    if(!overlay.route.views.every(v=>v.position.length===3 && v.position.every(Number.isFinite)))throw Error('Invalid route positions');
    await page.mouse.move(rect.x+rect.width*.5,rect.y+rect.height*.5);await page.mouse.wheel(0,850);await page.waitForTimeout(500);await ready();
    if(overlay.bbox.corners.length!==8)throw Error('Missing oriented bbox corners');
    const currentUp=await page.locator('#up-x, #up-y, #up-z').evaluateAll(els=>els.map(el=>Number(el.value)));
    const norm=Math.hypot(...currentUp);
    if(overlay.bbox.axes[2].some((x,i)=>Math.abs(x-currentUp[i]/norm)>1e-5))throw Error('BBox not aligned to up');
    if(!overlay.route.views.every(v=>v.frustum?.depth>0 && v.frustum.forward.length===3))throw Error('Missing frustum geometry');
    if(await page.locator('#show-frusta').count())throw Error('Separate frustum checkbox still present');
    if(!overlay.route.origin_frustum?.depth || JSON.stringify(overlay.route.origin_frustum.position)!==JSON.stringify(overlay.route.origin))throw Error('Missing initial-view frustum');
    const pixelsOff=await canvas.evaluate(c=>c.toDataURL());
    await page.locator('#show-route').check();
    if(await canvas.evaluate(c=>c.toDataURL())===pixelsOff)throw Error('No combined route and frustum pixels drawn');
    await page.screenshot({path:'test-results/visualization-route-frusta.png'});
    await page.locator('#show-route').uncheck();
    if(await canvas.evaluate(c=>c.toDataURL())!==pixelsOff)throw Error('Frustum toggle changed base render');
    await page.locator('#show-bbox').check();await page.locator('#show-route').check();
    if(await canvas.evaluate(c=>c.toDataURL())===pixelsOff)throw Error('No overlay pixels drawn');
    await page.screenshot({path:'test-results/visualization-bbox-route.png'});
    const before=JSON.stringify(overlay.projection);
    await page.mouse.move(rect.x+rect.width*.5,rect.y+rect.height*.5);await page.mouse.down();await page.mouse.move(rect.x+rect.width*.6,rect.y+rect.height*.55);await page.mouse.up();await ready();
    if(JSON.stringify(overlay.projection)===before)throw Error('Camera projection did not update');
    await page.screenshot({path:'test-results/visualization-orbit.png'});
    await page.locator('#up-x').fill('0');await page.locator('#up-y').fill('-1');await page.locator('#up-z').fill('0');
    await page.locator('#camera-apply').click();await ready();
    if(overlay.bbox.axes[2].some((v,i)=>Math.abs(v-[0,-1,0][i])>1e-5))throw Error('BBox did not follow new up');
    await page.locator('#show-bbox').uncheck();await page.locator('#show-route').uncheck();
    await page.setViewportSize({width:390,height:844});await page.waitForTimeout(700);await ready();
    if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
    if(errors.length)throw Error(errors.join('\n'));
    console.log('Real SAM2 upright bbox, initial and six drone frusta, combined toggle, new up, orbit, mobile OK');await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
